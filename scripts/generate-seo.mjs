const coreVersion = JSON.parse(fs.readFileSync(path.join(root, "core/package.json"), "utf8")).version;
const decode = value => value.replace(/&quot;/g, '"').replace(/\\n/g, " ").replace(/\$\{coreVersion\}/g, coreVersion).replace(/\s+/g, " ").trim();
const SUFFIX = {
  components: "Forge UI 中文后台 React 组件库，附完整参数说明和可复制代码。",
  cases: "Forge UI 中文后台 React 组件库的可操作案例，直接在页面上试。",
};
const withNoun = title => /(组件|规范|布局)$/.test(title) ? title : `${title}组件`;
const attribute = (source, tag, name) => {
  const element = source.match(new RegExp(`<${tag}\\b[\\s\\S]*?/?>`));
  const match = element?.[0].match(new RegExp(`\\b${name}=(?:"([^"]*)"|\\{"([^"]*)"\\}|\\{\`([^\`]*)\`\\})`));
  return match ? decode(match[1] ?? match[2] ?? match[3]) : null;
};

function pageRoutes(section) {
  const routes = [];
  const walk = dir => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (!entry.isDirectory() || entry.name.startsWith("_") || entry.name.startsWith("[")) continue;
      const folder = path.join(dir, entry.name);
      if (fs.existsSync(path.join(folder, "page.tsx"))) routes.push(folder);
      walk(folder);
    }
  };
  walk(path.join(app, section));
  if (fs.existsSync(path.join(app, section, "page.tsx"))) routes.push(path.join(app, section));
  return routes.map(folder => ({ folder, route: "/" + path.relative(app, folder).split(path.sep).join("/") }));
}

const pages = { ...STATIC };
const layouts = [];
for (const section of ["components", "cases", "docs"]) {
  for (const { folder, route } of pageRoutes(section)) {
    const source = fs.readFileSync(path.join(folder, "page.tsx"), "utf8");
    if (/redirect\(|LegacyInteractionRedirect/.test(source)) pages[route] = { title: "跳转", description: "", noindex: true };
    else if (!pages[route]) {
      const heading = section === "docs" ? "DocHeader" : "PageHeading";
      const title = attribute(source, heading, "title");
      const description = attribute(source, heading, section === "docs" ? "description" : "hint");
      if (!title) throw new Error(`No ${heading} title in ${route}; add it to STATIC in scripts/generate-seo.mjs`);
      if (section === "docs") pages[route] = { title, description: description ?? `Forge UI 文档：${title}。` };
      else {
        const lead = (description ?? `${title}的效果、用法和参数。`).replace(/[。.]?$/, "。");
        pages[route] = { title: withNoun(title) + (section === "components" ? " · 用法与参数" : " · 效果与案例"), description: lead + SUFFIX[section] };
      }
    }
    if (route !== `/${section}` || section === "docs") layouts.push({ folder, route });
  }
}
for (const file of fs.readdirSync(path.join(root, "content/guides")).filter(name => name.endsWith(".md")).sort()) {
  const lines = fs.readFileSync(path.join(root, "content/guides", file), "utf8").split("\n");
  const title = lines.find(line => line.startsWith("# "))?.slice(2).trim();
  const paragraph = lines.find(line => line.trim() && !/^(#|>|-|\*|\d+\.|```|\|)/.test(line.trim()));
  pages[`/guides/${file.slice(0, -3)}`] = { title: `${title} · 使用指南`, description: decode(paragraph ?? title).replace(/[`*]/g, "").slice(0, 120) };
}

for (const file of fs.readdirSync(path.join(root, "content/articles")).filter(name => name.endsWith(".md")).sort()) {
  const front = fs.readFileSync(path.join(root, "content/articles", file), "utf8").match(/^---\n([\s\S]*?)\n---\n/)?.[1] ?? "";
  const field = key => front.match(new RegExp(`^${key}:\\s*(.+)$`, "m"))?.[1].trim();
  if (!field("title") || !field("description")) throw new Error(`content/articles/${file} needs title and description`);
  pages[`/articles/${file.slice(0, -3)}`] = { title: field("title"), description: field("description") };
}

const json = JSON.stringify(Object.fromEntries(Object.entries(pages).sort(([a], [b]) => a.localeCompare(b))), null, 2) + "\n";
const layoutSource = route => `${MARKER}\nimport type { ReactNode } from "react";\nimport { pageMetadata } from "@/lib/seo";\n\nexport const metadata = pageMetadata(${JSON.stringify(route)});\n\nexport default function Layout({ children }: { children: ReactNode }) {\n  return children;\n}\n`;

const problems = [];
const write = (file, content) => {
  const target = path.join(root, file);
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
  if (current === content) return;
  if (check) problems.push(`stale: ${file}`);
  else { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, content); }
};
write(OUTPUT, json);
for (const { folder, route } of layouts) {
  const file = path.relative(root, path.join(folder, "layout.tsx"));
  const existing = fs.existsSync(path.join(root, file)) ? fs.readFileSync(path.join(root, file), "utf8") : null;
  if (existing && !existing.startsWith(MARKER)) {
    if (!existing.includes(`pageMetadata(${JSON.stringify(route)})`)) problems.push(`${file} exists; export metadata = pageMetadata(${JSON.stringify(route)}) there`);
    continue;
  }
  write(file, layoutSource(route));
}
for (const { folder, route } of layouts) {
  if (/export const metadata|generateMetadata/.test(fs.readFileSync(path.join(folder, "page.tsx"), "utf8"))) problems.push(`${route}/page.tsx exports its own metadata; remove it so the generated layout applies`);
}
if (problems.length) {
  console.error(problems.join("\n") + (check ? "\nRun node scripts/generate-seo.mjs" : ""));
  process.exit(1);
}
console.log(`SEO metadata ${check ? "verified" : "written"}: ${Object.keys(pages).length} pages, ${layouts.length} route layouts`);
