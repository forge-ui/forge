//   node scripts/generate-seo.mjs          # write src/app/_seo/pages.json and missing route layouts
//   node scripts/generate-seo.mjs --check  # fail when either is stale
// Component and case pages are client components, so their metadata lives in a generated
// sibling layout.tsx that calls pageMetadata(path) from src/lib/seo.ts.
